//! Scan `contracts/fixtures/` at build time and emit a static table of
//! (name, input, expected) triples using include_str!, so the WASM
//! conformance suite replays the exact same fixtures as the native one
//! without filesystem access at runtime.

use std::fmt::Write;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let fixtures = manifest
        .parent()
        .and_then(|p| p.parent())
        .expect("workspace root")
        .join("contracts")
        .join("fixtures");

    println!("cargo:rerun-if-changed={}", fixtures.display());

    let mut out = String::new();
    out.push_str("// GENERATED by build.rs — do not edit.\n");
    out.push_str("pub struct Fixture {\n    pub name: &'static str,\n    pub input: &'static str,\n    pub expected: &'static str,\n}\n\n");

    for category in ["sse", "ollama", "api", "models", "thinking", "settings"] {
        let dir = fixtures.join(category);
        let mut entries = String::new();
        if dir.is_dir() {
            let mut cases: Vec<PathBuf> = std::fs::read_dir(&dir)
                .expect("read fixture category")
                .flatten()
                .map(|e| e.path())
                .filter(|p| p.is_dir())
                .collect();
            cases.sort();
            for case in cases {
                let name = case.file_name().unwrap().to_string_lossy().to_string();
                let input = case.join("input.txt");
                let expected = case.join("expected.json");
                assert!(input.is_file(), "missing {}", input.display());
                assert!(expected.is_file(), "missing {}", expected.display());
                let _ = writeln!(
                    &mut entries,
                    "    Fixture {{ name: {:?}, input: include_str!({:?}), expected: include_str!({:?}) }},",
                    name,
                    input,
                    expected
                );
            }
        }
        let _ = writeln!(
            out,
            "pub static {}: &[Fixture] = &[\n{}];\n",
            category.to_uppercase(),
            entries
        );
    }

    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("fixtures.rs");
    std::fs::write(dest, out).expect("write fixtures.rs");
}
